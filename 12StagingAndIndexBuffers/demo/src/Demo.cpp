#include "Demo.hpp"

// =============================================================================
void Demo::submit_draws(vkl::Renderer &renderer) {
    renderer.submit({
        .mesh = _xy_plane
    });
}

// =============================================================================
void Demo::init() {
    _xy_plane.init(
        0.5f,
        {{
            { 1.0f, 0.0f, 0.0f, 1.0f }, // Red
            { 0.0f, 1.0f, 0.0f, 1.0f }, // Green
            { 0.0f, 0.0f, 1.0f, 1.0f }, // Blue
            { 1.0f, 1.0f, 1.0f, 1.0f }, // White
        }}
    );
}

// =============================================================================
void Demo::shutdown() {
    _xy_plane.shutdown();
}

// =============================================================================
Demo::Demo() :
    _xy_plane    { }
{ }
